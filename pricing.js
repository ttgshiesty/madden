    function startCheckout(priceId) {
      var wrap = document.getElementById('pricingCheckoutWrap');
      var mount = document.getElementById('pricingCheckoutMount');
      var label = document.getElementById('pricingCheckoutLabel');
      if (!wrap || !mount || !stripePk) return;
      // Funnel: Subscribe click on the pricing page → tells us how many
      // visitors get to Stripe but never finish. Pairs with s2_upgrade_clicked
      // (snipes path) and payment_completed (Stripe success).
      try { if (window.posthog) window.posthog.capture('payment_started', { source: 'pricing_page', price_id: priceId }); } catch (_) {}

      // Hide pricing cards, show checkout
      document.querySelector('.pricing-cards').style.display = 'none';
      wrap.style.display = '';
      mount.innerHTML = '<div class="loading"><div class="spinner"></div><p>Loading checkout...</p></div>';
      label.textContent = priceId.includes('1TXJ15') ? 'Founding Member — $10/mo' : 'Pro — $30/mo';

      if (pricingCheckout) { pricingCheckout.destroy(); pricingCheckout = null; }

      fetch('/api/checkout', {
        method: 'POST',
        headers: { 'Content-Type': 'application/json' },
        body: JSON.stringify({ priceId: priceId })
      })
        .then(function(r) { return r.json(); })
        .then(function(data) {
          if (!data.clientSecret) { mount.innerHTML = '<p style="color:#ff4444">Failed to load checkout.</p>'; return; }
          var stripe = Stripe(stripePk);
          return stripe.createEmbeddedCheckoutPage({ clientSecret: data.clientSecret });
        })
        .then(function(checkout) {
          if (!checkout) return;
          pricingCheckout = checkout;
          mount.innerHTML = '';
          checkout.mount('#pricingCheckoutMount');
        })
        .catch(function() { mount.innerHTML = '<p style="color:#ff4444">Failed to load checkout. Please try again.</p>'; });

      wrap.scrollIntoView({ behavior: 'smooth', block: 'start' });
    }

    function hideCheckout() {
      var wrap = document.getElementById('pricingCheckoutWrap');
      if (wrap) wrap.style.display = 'none';
      document.querySelector('.pricing-cards').style.display = '';
      if (pricingCheckout) { pricingCheckout.destroy(); pricingCheckout = null; }
    }
